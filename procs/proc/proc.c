static ATOMIC_UINT8_T s_pid;

/* ========================================================================== */
/*                           Function Definition                              */
/* ========================================================================== */

void proc_id_set(proc_id_e pid)
{
    ATOM_STORE(&s_pid, pid, MORDER_RELAXED);
}

proc_id_e proc_id_get()
{
    return ATOM_LOAD(&s_pid, MORDER_RELAXED);
}

int proc_current_is_core()
{
    return proc_id_get() == PID_CORE ? 1 : 0;
}